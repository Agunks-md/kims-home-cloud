/** Map MIME type ke icon component */
export function getFileIcon(mimeType: string): React.ReactElement {
  if (mimeType.startsWith("image/")) return <ImageIcon size={18} />;
  if (mimeType.startsWith("video/")) return <VideoIcon size={18} />;
  if (mimeType.startsWith("audio/")) return <MusicIcon size={18} />;
  if (mimeType.includes("zip") || mimeType.includes("rar") || mimeType.includes("7z") || mimeType.includes("tar"))
    return <ZipIcon size={18} />;
  return <FileIcon size={18} />;
}
